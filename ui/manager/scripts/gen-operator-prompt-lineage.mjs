#!/usr/bin/env node
/**
 * Regenerates `src/lib/operator/operator-prompt-lineage.json`: a hash of every
 * line any shipped default of the operator's instructions has ever contained.
 *
 * Why: an admin who trimmed the default (6.7.0's setup-api capped the prompt at
 * 100k characters, so several did) has `promptBodyIsDefault: false`, and the
 * upgrade dialog used to treat that as "your own edits, keep them" — while the
 * text was in fact an old or shortened default whose only difference from the
 * new one was what it lacked. With this list the dialog can tell "only removes
 * lines / only keeps an earlier default's wording" (preselect the new default)
 * from "adds text the Manager never shipped" (keep it). See prompt-lineage.ts.
 *
 * How: every commit that touched system-prompt.ts is RENDERED, not grepped —
 * the stored body is what `defaultOperatorPromptBody(scope)` returned, with
 * template escapes resolved, the model catalogue built from MODEL_SUGGESTIONS
 * and sections gated on the granted endpoints. Each historical module graph is
 * loaded straight out of git (a module-loader hook serves `git show <sha>:path`,
 * TypeScript stripped by Node), so no checkout is needed. A commit whose graph
 * no longer loads is reported and skipped; it is never approximated, because
 * an over-wide list would make the dialog preselect "replace" over real edits.
 *
 * Run from ui/manager:  node scripts/gen-operator-prompt-lineage.mjs
 * Needs Node >= 23 (module.stripTypeScriptTypes) and the full git history.
 * When to run: in the PR that bumps operator-revision.json, so the revision it
 * leaves behind is on the list (operator-prompt-lineage.test.ts says so when it
 * is overdue).
 */
import { execFileSync } from "node:child_process";
import { register } from "node:module";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url));
const managerDir = path.resolve(here, "..");
const repoRoot = execFileSync("git", ["rev-parse", "--show-toplevel"], { cwd: managerDir, encoding: "utf8" }).trim();
const PROMPT = "ui/manager/src/lib/operator/system-prompt.ts";
const OUT = path.join(managerDir, "src/lib/operator/operator-prompt-lineage.json");

/** 32-bit FNV-1a, hex — the same function prompt-lineage.ts applies at runtime. */
function fnv1a(text) {
  let hash = 0x811c9dc5;
  for (let i = 0; i < text.length; i++) {
    hash ^= text.charCodeAt(i);
    hash = Math.imul(hash, 0x01000193) >>> 0;
  }
  return hash.toString(16).padStart(8, "0");
}

/** Identical to `normalizeLine` in prompt-lineage.ts. */
function normalizeLine(line) {
  return line.replace(/\s+/g, " ").trim();
}

register(new URL("./lib/git-module-loader.mjs", import.meta.url), {
  parentURL: import.meta.url,
  data: { repoRoot },
});

const shas = execFileSync("git", ["log", "--format=%H", "--", PROMPT], { cwd: repoRoot, encoding: "utf8" })
  .trim()
  .split("\n")
  .filter(Boolean);

const hashes = new Set();
const failed = [];
let rendered = 0;
for (const sha of shas) {
  const url = `gitsrc:///${sha}/${PROMPT}`;
  try {
    const mod = await import(url);
    const scopes = ["read_only", "read_write"];
    let any = false;
    for (const scope of scopes) {
      let body;
      if (typeof mod.defaultOperatorPromptBody === "function") body = mod.defaultOperatorPromptBody(scope);
      else if (typeof mod.DEFAULT_OPERATOR_PROMPT_BODY === "string") body = mod.DEFAULT_OPERATOR_PROMPT_BODY;
      if (typeof body !== "string") continue;
      any = true;
      for (const line of body.replace(/\r\n/g, "\n").split("\n")) {
        const normalized = normalizeLine(line);
        if (normalized) hashes.add(fnv1a(normalized));
      }
    }
    if (any) rendered++;
    else failed.push(`${sha.slice(0, 10)} (no default body export)`);
  } catch (error) {
    failed.push(`${sha.slice(0, 10)} (${String(error?.message ?? error).split("\n")[0]})`);
  }
}

const revision = JSON.parse(readFileSync(path.join(managerDir, "src/lib/operator/operator-revision.json"), "utf8")).revision;
const out = {
  $comment:
    "Generated by scripts/gen-operator-prompt-lineage.mjs — FNV-1a hashes of every non-blank line of every shipped default operator prompt body (both scopes). Do not edit by hand.",
  throughRevision: revision,
  renderedCommits: rendered,
  lines: [...hashes].sort(),
};
writeFileSync(OUT, `${JSON.stringify(out, null, 2)}\n`);
console.log(`rendered ${rendered} of ${shas.length} commits, ${hashes.size} distinct lines, through revision ${revision}`);
if (failed.length) console.log(`skipped ${failed.length}:\n  ${failed.join("\n  ")}`);
