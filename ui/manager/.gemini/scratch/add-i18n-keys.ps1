foreach ($locale in $translations.Keys) {
  $filePath = Join-Path $localesDir "$locale.json"
  $content = Get-Content $filePath -Raw -Encoding UTF8
  
  # Find the last closing brace } which closes the root object
  # We need to insert before it, after adding a comma to the previous section
  $lastBraceIndex = $content.LastIndexOf('}')
  # Find the second-to-last } which closes the last section
  $secondLastBraceIndex = $content.LastIndexOf('}', $lastBraceIndex - 1)
  
  # Insert a comma after the second-to-last }, then add the new section
  $before = $content.Substring(0, $secondLastBraceIndex + 1)
  $after = $content.Substring($secondLastBraceIndex + 1)
  
  $newContent = $before + "," + "`r`n" + $translations[$locale] + $after
  
  [System.IO.File]::WriteAllText($filePath, $newContent, [System.Text.Encoding]::UTF8)
  Write-Host "Updated $locale.json"
}

Write-Host "Done! All 10 locale files updated."
