import lineage from "./operator-prompt-lineage.json";

/**
 * Where the operator's stored instructions came from, as far as the upgrade
 * dialog needs to know: is there anything in them the Manager never shipped?
 *
 * `promptBodyIsDefault: false` only says the text is not today's default at
 * activation. In practice that was very often a TRIMMED default — 6.7.0's
 * setup-api capped the prompt at 100k characters, and the fix was to delete
 * sections — or an older default carried through a reconfigure. The upgrade
 * dialog read every such body as "your own edits" and preselected keeping it, so
 * the admin who clicked through kept a shortened prompt and none of what the
 * upgrade was for.
 *
 * The test here is set membership, line by line, not a diff. A diff counts a
 * moved line as added, and `diffLines` reports everything as changed past 2000
 * lines; neither says "did the admin write this". A line is *known* when it is in
 * the new default or in any default the Manager has shipped before
 * (`operator-prompt-lineage.json`, generated by
 * `scripts/gen-operator-prompt-lineage.mjs` from every historical version of the
 * prompt, rendered). Every other non-blank line, however short, is the admin's.
 *
 * Errors fall toward KEEPING the text: a hash collision or a line the generator
 * could not render makes a body look edited, never the reverse.
 */

export type InstructionsLineage =
  /** Every line is in the new default — the text only lacks some of it (or is identical). */
  | "only-removes"
  /** Every line is in the new default or an earlier shipped default — an old or trimmed default. */
  | "older-default"
  /** Some line was never in any shipped default: the admin wrote it. */
  | "edited";

export interface InstructionsLineageReport {
  lineage: InstructionsLineage;
  /** Non-blank lines found in no shipped default. */
  foreignLines: number;
  /** Non-blank lines from an earlier default that the new one no longer has. */
  olderDefaultLines: number;
  /** Non-blank lines of the new default the stored text lacks. */
  missingLines: number;
}

/** Whitespace-insensitive line identity, shared with the generator. */
export function normalizeLine(line: string): string {
  return line.replace(/\s+/g, " ").trim();
}

/** 32-bit FNV-1a, hex — the generator's hash. */
export function lineHash(text: string): string {
  let hash = 0x811c9dc5;
  for (let i = 0; i < text.length; i++) {
    hash ^= text.charCodeAt(i);
    hash = Math.imul(hash, 0x01000193) >>> 0;
  }
  return hash.toString(16).padStart(8, "0");
}

const SHIPPED: ReadonlySet<string> = new Set(lineage.lines);

/** The revision the shipped-line list was last generated at. */
export const PROMPT_LINEAGE_THROUGH_REVISION: number = lineage.throughRevision;

function nonBlankLines(text: string): string[] {
  return text
    .replace(/\r\n/g, "\n")
    .split("\n")
    .map(normalizeLine)
    .filter((line) => line.length > 0);
}

/**
 * Classify stored instructions against the new default.
 *
 * `shipped` is injectable for tests; production uses the generated list.
 */
export function classifyInstructions(
  stored: string,
  newDefault: string,
  shipped: ReadonlySet<string> = SHIPPED,
): InstructionsLineageReport {
  const current = new Set(nonBlankLines(newDefault));
  const storedLines = nonBlankLines(stored);
  const storedSet = new Set(storedLines);
  let foreignLines = 0;
  let olderDefaultLines = 0;
  for (const line of storedLines) {
    if (current.has(line)) continue;
    if (shipped.has(lineHash(line))) olderDefaultLines++;
    else foreignLines++;
  }
  let missingLines = 0;
  for (const line of current) if (!storedSet.has(line)) missingLines++;
  const lineage: InstructionsLineage =
    foreignLines > 0 ? "edited" : olderDefaultLines > 0 ? "older-default" : "only-removes";
  return { lineage, foreignLines, olderDefaultLines, missingLines };
}
