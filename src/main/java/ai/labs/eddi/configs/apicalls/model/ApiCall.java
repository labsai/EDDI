package ai.labs.eddi.configs.apicalls.model;

import java.util.List;
import java.util.Map;

public class ApiCall {
    /**
     * {@link #unknownFields}: refuse the call. The default when a schema is set.
     */
    public static final String UNKNOWN_FIELDS_REJECT = "reject";
    /** {@link #unknownFields}: remove the undeclared field and send the rest. */
    public static final String UNKNOWN_FIELDS_DROP = "drop";
    /** {@link #unknownFields}: pass the undeclared field through. */
    public static final String UNKNOWN_FIELDS_ALLOW = "allow";

    private String name;
    /**
     * Natural language description for LLM agents.
     */
    private String description;
    /**
     * Map of parameter name to parameter description for LLM agents.
     */
    private Map<String, String> parameters;
    private List<String> actions;
    private Boolean saveResponse = false;
    private String responseObjectName;
    private String responseHeaderObjectName;
    private Boolean fireAndForget = false;
    private Boolean isBatchCalls = false;
    private String iterationObjectName;
    /**
     * Request timeout for this call in milliseconds. {@code null} falls back to the
     * deployment-wide default ({@code eddi.httpcalls.default-timeout-millis}).
     */
    private Integer timeoutInMillis;
    /**
     * How much of the response body is kept in conversation memory, in bytes. A
     * larger body is <em>truncated</em> at this size (with a warning) rather than
     * failing the call — the call itself only fails if the response exceeds the
     * engine's much higher transport ceiling, which no configuration can lower.
     * {@code null} falls back to the deployment-wide default
     * ({@code eddi.httpcalls.default-max-response-size-bytes}, 2 MB).
     */
    private Integer maxResponseSizeInBytes;
    /**
     * Run the call once per element of an array and collect every element's result
     * into one array. {@code null} (the default) sends exactly one request, as
     * before. See {@link ForEachInstruction}.
     */
    private ForEachInstruction forEach;
    /**
     * JSON Schema of the tool arguments an LLM may pass to this call: one object
     * whose properties are the tool parameters (path and query values, and the
     * request body variable with its own nested schema). Generated by the OpenAPI
     * tool builder and settable by hand.
     * <p>
     * <b>Absence is a switch:</b> {@code null} (every config written before this
     * field existed) means no argument validation, string-typed tool parameters and
     * the request rendered exactly as before. When set, a tool call whose arguments
     * violate it is refused before the approval gate and never executed, and
     * non-string argument values are rendered as JSON text. Supported keywords:
     * {@code type}, {@code properties}, {@code required}, {@code items},
     * {@code enum}, {@code additionalProperties} (boolean), {@code description},
     * {@code nullable}, {@code minimum}/{@code maximum},
     * {@code minLength}/{@code maxLength}, {@code minItems}/{@code maxItems};
     * anything else (including {@code $ref}, {@code pattern} and {@code format}) is
     * ignored.
     */
    private Map<String, Object> argumentSchema;
    /**
     * What happens to an argument field {@link #argumentSchema} does not declare,
     * in every object that declares {@code properties}: {@code "reject"} refuses
     * the call, {@code "drop"} removes the field before the request is built,
     * {@code "allow"} passes it through. An explicit
     * {@code additionalProperties: true} keeps the field under every mode; an
     * explicit {@code false} is refused under {@code reject} and {@code allow} and
     * removed under {@code drop}, which also guarantees it is never sent.
     * <p>
     * <b>A default, not a switch:</b> {@code null} means {@code "reject"} whenever
     * a schema is set (a silently ignored field is the failure the schema exists to
     * catch) and has no effect without one.
     */
    private String unknownFields;
    private HttpPreRequest preRequest;
    private Request request;
    private HttpPostResponse postResponse;

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getDescription() {
        return description;
    }

    public void setDescription(String description) {
        this.description = description;
    }

    public Map<String, String> getParameters() {
        return parameters;
    }

    public void setParameters(Map<String, String> parameters) {
        this.parameters = parameters;
    }

    public List<String> getActions() {
        return actions;
    }

    public void setActions(List<String> actions) {
        this.actions = actions;
    }

    public Boolean getSaveResponse() {
        return saveResponse;
    }

    public void setSaveResponse(Boolean saveResponse) {
        this.saveResponse = saveResponse;
    }

    public String getResponseObjectName() {
        return responseObjectName;
    }

    public void setResponseObjectName(String responseObjectName) {
        this.responseObjectName = responseObjectName;
    }

    public String getResponseHeaderObjectName() {
        return responseHeaderObjectName;
    }

    public void setResponseHeaderObjectName(String responseHeaderObjectName) {
        this.responseHeaderObjectName = responseHeaderObjectName;
    }

    public Boolean getFireAndForget() {
        return fireAndForget;
    }

    public void setFireAndForget(Boolean fireAndForget) {
        this.fireAndForget = fireAndForget;
    }

    public Boolean getIsBatchCalls() {
        return isBatchCalls;
    }

    public void setIsBatchCalls(Boolean isBatchCalls) {
        this.isBatchCalls = isBatchCalls;
    }

    public String getIterationObjectName() {
        return iterationObjectName;
    }

    public void setIterationObjectName(String iterationObjectName) {
        this.iterationObjectName = iterationObjectName;
    }

    public Integer getTimeoutInMillis() {
        return timeoutInMillis;
    }

    public void setTimeoutInMillis(Integer timeoutInMillis) {
        this.timeoutInMillis = timeoutInMillis;
    }

    public Integer getMaxResponseSizeInBytes() {
        return maxResponseSizeInBytes;
    }

    public void setMaxResponseSizeInBytes(Integer maxResponseSizeInBytes) {
        this.maxResponseSizeInBytes = maxResponseSizeInBytes;
    }

    public ForEachInstruction getForEach() {
        return forEach;
    }

    public void setForEach(ForEachInstruction forEach) {
        this.forEach = forEach;
    }

    public Map<String, Object> getArgumentSchema() {
        return argumentSchema;
    }

    public void setArgumentSchema(Map<String, Object> argumentSchema) {
        this.argumentSchema = argumentSchema;
    }

    public String getUnknownFields() {
        return unknownFields;
    }

    public void setUnknownFields(String unknownFields) {
        this.unknownFields = unknownFields;
    }

    public HttpPreRequest getPreRequest() {
        return preRequest;
    }

    public void setPreRequest(HttpPreRequest preRequest) {
        this.preRequest = preRequest;
    }

    public Request getRequest() {
        return request;
    }

    public void setRequest(Request request) {
        this.request = request;
    }

    public HttpPostResponse getPostResponse() {
        return postResponse;
    }

    public void setPostResponse(HttpPostResponse postResponse) {
        this.postResponse = postResponse;
    }

    /** Whether {@code value} is a policy {@link #unknownFields} accepts. */
    public static boolean isKnownUnknownFields(String value) {
        if (value == null || value.isBlank()) {
            return true;
        }
        String trimmed = value.trim();
        return UNKNOWN_FIELDS_REJECT.equalsIgnoreCase(trimmed) || UNKNOWN_FIELDS_DROP.equalsIgnoreCase(trimmed)
                || UNKNOWN_FIELDS_ALLOW.equalsIgnoreCase(trimmed);
    }
}
